import Foundation

/// Pasteboard type identifiers Clips reads and writes. Strings, so the core needs no AppKit.
public enum PasteboardType {
    public static let string = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"

    /// nspasteboard.org markers. Password managers set Concealed; apps set Transient for
    /// short-lived data and AutoGenerated for content the user didn't copy themselves.
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Bundle id of the app that wrote the pasteboard, when the app says so.
    public static let source = "org.nspasteboard.source"

    /// Older private markers some apps still use instead of the nspasteboard.org ones.
    public static let legacySkipMarkers: Set<String> = [
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]

    /// Any of these on the pasteboard means "don't record this".
    public static let skipMarkers: Set<String> = legacySkipMarkers.union([concealed, transient, autoGenerated])

    public static let imageTypes = [png, tiff, jpeg, heic]
    public static let richTextTypes = [rtf, html, rtfd]

    /// Everything Clips stores, in order of preference within an item.
    public static let stored: [String] = [string, rtf, html, rtfd, url, fileURL, png, tiff, jpeg, heic]
}
