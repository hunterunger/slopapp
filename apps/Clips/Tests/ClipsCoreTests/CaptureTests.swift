private let now = Date(timeIntervalSinceReferenceDate: 800_000_000)

private func rep(_ type: String, _ text: String) -> Representation {
    Representation(type: type, data: Data(text.utf8))
}

private func build(_ snapshot: PasteboardSnapshot, maxBytes: Int = 50_000_000) -> Result<(Clip, ClipPayload), SkipReason> {
    ClipBuilder.build(snapshot, sourceBundleID: "com.apple.TextEdit", sourceName: "TextEdit", now: now, maxBytes: maxBytes)
}

/// A real PNG of the given size, made with ImageIO.
func makePNG(width: Int, height: Int) -> Data {
    let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                            space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)!
    context.setFillColor(CGColor(red: 0.2, green: 0.5, blue: 0.8, alpha: 1))
    context.fill(CGRect(x: 0, y: 0, width: width, height: height))
    let image = context.makeImage()!
    let data = NSMutableData()
    let destination = CGImageDestinationCreateWithData(data, UTType.png.identifier as CFString, 1, nil)!
    CGImageDestinationAddImage(destination, image, nil)
    CGImageDestinationFinalize(destination)
    return data as Data
}

@Suite struct CapturePolicyTests {
    let settings = CaptureSettings(ignoredBundleIDs: ["com.1password.1password"])

    @Test(arguments: [PasteboardType.concealed, PasteboardType.transient, PasteboardType.autoGenerated,
                      "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"])
    func skipsMarkedContent(marker: String) {
        let decision = CapturePolicy.decide(types: [PasteboardType.string, marker], sourceBundleID: nil, settings: settings)
        #expect(decision == .skip(.marked(marker)))
    }

    @Test func skipsIgnoredApps() {
        let decision = CapturePolicy.decide(types: [PasteboardType.string], sourceBundleID: "com.1password.1password", settings: settings)
        #expect(decision == .skip(.ignoredApp("com.1password.1password")))
    }

    @Test func skipsWhilePaused() {
        var paused = settings
        paused.isPaused = true
        #expect(CapturePolicy.decide(types: [PasteboardType.string], sourceBundleID: nil, settings: paused) == .skip(.paused))
    }

    @Test func skipsTypesWeDontStore() {
        #expect(CapturePolicy.decide(types: ["com.example.private"], sourceBundleID: nil, settings: settings) == .skip(.empty))
    }

    @Test func recordsOrdinaryText() {
        #expect(CapturePolicy.decide(types: [PasteboardType.string, PasteboardType.rtf], sourceBundleID: "com.apple.TextEdit", settings: settings) == .record)
    }

    @Test func presetsIncludePasswordManagers() {
        let ids = Set(IgnoredApp.presets.map(\.bundleID))
        #expect(ids.contains("com.1password.1password"))
        #expect(ids.contains("com.apple.Passwords"))
        #expect(ids.contains("com.bitwarden.desktop"))
    }
}

@Suite struct ClipBuilderTests {
    @Test func plainText() throws {
        let (clip, payload) = try build(PasteboardSnapshot(text: "slopapp-test hello\nworld")).get()
        #expect(clip.kind == .text)
        #expect(clip.text == "slopapp-test hello\nworld")
        #expect(clip.sourceName == "TextEdit")
        #expect(!clip.hasRichText)
        #expect(payload.items.count == 1)
        #expect(payload.items[0].map(\.type) == [PasteboardType.string])
    }

    @Test func keepsRichTextAlongsidePlain() throws {
        let snapshot = PasteboardSnapshot(items: [[rep(PasteboardType.string, "Bold"), rep(PasteboardType.rtf, "{\\rtf1 Bold}"),
                                                   rep(PasteboardType.html, "<b>Bold</b>")]])
        let (clip, payload) = try build(snapshot).get()
        #expect(clip.hasRichText)
        #expect(payload.items[0].map(\.type) == [PasteboardType.string, PasteboardType.rtf, PasteboardType.html])
        #expect(payload.plainText()?.items == [[rep(PasteboardType.string, "Bold")]])
    }

    @Test(arguments: ["https://example.com/a?b=c", "http://localhost:3000", "mailto:someone@example.com", "www.example.com"])
    func detectsLinks(text: String) throws {
        #expect(try build(PasteboardSnapshot(text: text)).get().0.kind == .link)
    }

    @Test(arguments: ["see https://example.com", "https://", "example", "file:///etc/hosts", "javascript:alert(1)"])
    func otherTextIsNotALink(text: String) throws {
        #expect(try build(PasteboardSnapshot(text: text)).get().0.kind != .link)
    }

    @Test func linkFromURLTypeOnly() throws {
        let snapshot = PasteboardSnapshot(items: [[rep(PasteboardType.url, "https://example.com")]])
        let (clip, payload) = try build(snapshot).get()
        #expect(clip.kind == .link)
        #expect(payload.items[0].first?.type == PasteboardType.string)
    }

    @Test func colors() throws {
        #expect(try build(PasteboardSnapshot(text: "#FF8800")).get().0.kind == .color)
        #expect(ColorValue(hex: "#f80") == ColorValue(hex: "#FF8800"))
        #expect(ColorValue(hex: "#FF880080")?.alpha == Double(0x80) / 255)
        #expect(ColorValue(hex: "FF8800") == nil)
        #expect(ColorValue(hex: "#GG0000") == nil)
    }

    @Test func files() throws {
        let snapshot = PasteboardSnapshot(items: [
            [rep(PasteboardType.fileURL, "file:///tmp/clips-test/a.txt"), rep(PasteboardType.string, "a.txt")],
            [rep(PasteboardType.fileURL, "file:///tmp/clips-test/b%20c.png")],
        ])
        let (clip, payload) = try build(snapshot).get()
        #expect(clip.kind == .file)
        #expect(clip.filePaths == ["/tmp/clips-test/a.txt", "/tmp/clips-test/b c.png"])
        #expect(payload.items.count == 2)
        #expect(ClipText.title(of: clip) == "a.txt and 1 more")
    }

    @Test func images() throws {
        let png = makePNG(width: 40, height: 30)
        let (clip, _) = try build(PasteboardSnapshot(items: [[Representation(type: PasteboardType.png, data: png)]])).get()
        #expect(clip.kind == .image)
        #expect(clip.imageWidth == 40 && clip.imageHeight == 30)
        #expect(ClipText.title(of: clip) == "Image, 40 × 30")
        let thumb = ImageInfo.thumbnail(of: png, maxPixelSize: 20)
        #expect(thumb?.width == 20)
    }

    @Test func textWinsOverImageRenderings() throws {
        // Spreadsheets put both the cells' text and a picture of them on the pasteboard.
        let snapshot = PasteboardSnapshot(items: [[rep(PasteboardType.string, "A1\tB1"),
                                                   Representation(type: PasteboardType.tiff, data: makePNG(width: 4, height: 4))]])
        #expect(try build(snapshot).get().0.kind == .text)
    }

    @Test func blankTextIsSkipped() {
        #expect(throws: SkipReason.empty) { try build(PasteboardSnapshot(text: "  \n\t ")).get() }
    }

    @Test func tooLargeIsSkipped() {
        #expect(throws: SkipReason.tooLarge) { try build(PasteboardSnapshot(text: String(repeating: "x", count: 2_000)), maxBytes: 1_000).get() }
    }

    @Test func longTextIsCappedInMemoryButPastedInFull() throws {
        let long = String(repeating: "slopapp-test ", count: 2_000) // 26,000 characters
        let (clip, payload) = try build(PasteboardSnapshot(text: long)).get()
        #expect(clip.text.count == Clip.textLimit)
        #expect(clip.textLength == long.count)
        #expect(clip.isTruncated)
        #expect(payload.items[0][0].data.count == long.utf8.count)
    }

    @Test func sameTextSameFingerprint() throws {
        let a = try build(PasteboardSnapshot(text: "same")).get().0
        let b = try build(PasteboardSnapshot(items: [[rep(PasteboardType.string, "same"), rep(PasteboardType.rtf, "{}")]])).get().0
        #expect(a.fingerprint == b.fingerprint)
        #expect(a.id != b.id)
    }
}

@Suite struct ChangeTrackerTests {
    @Test func ignoresStartingContentAndRepeats() {
        var tracker = ChangeTracker(startingAt: 10)
        let atLaunch = tracker.isNewExternalChange(10) // what was there at launch isn't recorded
        let next = tracker.isNewExternalChange(11)
        let repeated = tracker.isNewExternalChange(11)
        #expect(!atLaunch && next && !repeated)
    }

    @Test func skipsOwnWrites() {
        var tracker = ChangeTracker(startingAt: 1)
        tracker.noteOwnWrite(2)
        let own = tracker.isNewExternalChange(2)
        let theirs = tracker.isNewExternalChange(3)
        #expect(!own && theirs)
    }

    @Test func coalescedChangesCountOnce() {
        var tracker = ChangeTracker(startingAt: 1)
        let first = tracker.isNewExternalChange(5) // several copies between two polls
        let again = tracker.isNewExternalChange(5)
        #expect(first && !again)
    }
}
