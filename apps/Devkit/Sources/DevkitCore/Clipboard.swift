import Foundation

/// The pasteboard, behind a protocol so tests (and scripted runs, via a private named
/// pasteboard) never touch the real clipboard.
public protocol Clipboard: AnyObject {
    var changeCount: Int { get }
    /// Type identifiers on the current item.
    var types: [String] { get }
    func string() -> String?
    /// A file copied in Finder, if any.
    func fileURL() -> URL?
    func setString(_ string: String)
    /// Image data (PNG or TIFF) on the clipboard, for reading QR codes.
    func imageData() -> Data?
    func setPNG(_ data: Data)
}

extension Clipboard {
    public func imageData() -> Data? { nil }
    public func setPNG(_ data: Data) {}
}

public enum ClipboardPolicy {
    /// nspasteboard.org markers that password managers and other apps set.
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    /// Automatic reads skip passwords and other content marked private or temporary.
    public static func allowsAutomaticRead(types: [String]) -> Bool {
        !types.contains(concealed) && !types.contains(transient) && !types.contains(autoGenerated)
    }
}

/// What to do with the clipboard when the user asks (Paste & Detect) or when the app is
/// activated with the opt-in setting on.
public final class ClipboardReader {
    public enum Outcome: Equatable, Sendable {
        /// A tool matched: switch to it with this input.
        case detected(Detector.Detection)
        /// Nothing matched: paste into the current tool.
        case unmatched(String)
        case noText
    }

    private var lastAutomaticChangeCount: Int?

    public init() {}

    /// Paste & Detect: always reads (the user asked), then detects.
    public func pasteAndDetect(from clipboard: Clipboard) -> Outcome {
        lastAutomaticChangeCount = clipboard.changeCount
        guard let text = clipboard.string(), !text.isEmpty else { return .noText }
        if let detection = Detector.detect(text) { return .detected(detection) }
        return .unmatched(text)
    }

    /// On activation: only when enabled, only once per clipboard change, never for
    /// concealed/transient content, and only acts when a tool matches.
    public func automaticRead(from clipboard: Clipboard, enabled: Bool) -> Detector.Detection? {
        guard enabled else { return nil }
        let count = clipboard.changeCount
        guard count != lastAutomaticChangeCount else { return nil }
        lastAutomaticChangeCount = count
        guard ClipboardPolicy.allowsAutomaticRead(types: clipboard.types), let text = clipboard.string() else { return nil }
        return Detector.detect(text)
    }

    /// Text we put on the clipboard ourselves (Copy Output) shouldn't bounce back in.
    public func noteOwnWrite(_ clipboard: Clipboard) {
        lastAutomaticChangeCount = clipboard.changeCount
    }
}
