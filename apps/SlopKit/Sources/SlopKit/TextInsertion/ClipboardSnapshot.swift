import AppKit

/// Everything on a pasteboard (every item, every type), so it can be put back exactly after an
/// app borrows the clipboard to paste: images, files and rich text survive, not just text.
/// Used by Dictate (pasting transcripts) and Shorthand (pasting long snippets).
public struct ClipboardSnapshot: Sendable, Equatable {
    public let items: [[String: Data]]

    public init(items: [[String: Data]]) {
        self.items = items
    }

    public var isEmpty: Bool { items.isEmpty }

    /// Marks a temporary write so clipboard managers (Clips) skip it (nspasteboard.org).
    public static let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]

    @MainActor
    public static func capture(_ pasteboard: NSPasteboard) -> ClipboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            var types: [String: Data] = [:]
            for type in item.types { if let data = item.data(forType: type) { types[type.rawValue] = data } }
            return types
        }.filter { !$0.isEmpty }
        return ClipboardSnapshot(items: items)
    }

    @MainActor
    public func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        pasteboard.writeObjects(items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: .init(type)) }
            return item
        })
    }

    /// Puts `text` on the pasteboard, marked transient when it's only borrowed. Returns the
    /// change count, so a later restore can tell whether someone copied something since.
    @MainActor @discardableResult
    public static func write(_ text: String, to pasteboard: NSPasteboard, transient: Bool) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient { for type in transientTypes { item.setString("", forType: type) } }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }
}
